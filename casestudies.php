                           <h4>How MQUAD Helped</h4>
                           <p>Data concerning key topics related to hotel choices were imported from SurveyMonkey into MQUAD.
                              Scarcliff Salvador then developed a coding system around key topics. After applying codes to all open-ended responses, the team used a code-weighting system of 1 to 10 indexing how important each factor is in wealthy visitors&#39; decision-making.
                              The MQUAD code-weighting system and code-weight descriptor bubble plots were particularly valuable. Factors that emerged as the most important in hotel choice were `Warmth,&#39; &#39;Luxury,&#39; and &#39;Sophistication.&#39; The code - weighting system allowed the team to index the relative degree of importance each characteristic played for each participant. Yet there was wide variation by income level toward these key factors.
                              So the team then turned to the MQUAD bubble plots to learn more. The code-weight bubble plot revealed four income-specific groups, each with distinct attitudes. After examining the tagged excerpts associated with each group, Scarcliff Salvador created summary composites for each and prepared recommendations to the developer.
                              Outcome: Using the MQUAD data analysis provided by Scarcliff Salavador, the property developer was able to customize the design, decor and staffing to embody those characteristics that prospective customers reported as most important to them.
                              Likewise, MQUAD made it easy for the firm to identify the natural language used by each unique target-market segment for use in marketing materials and messaging.

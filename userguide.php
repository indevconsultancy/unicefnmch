                     <h3>Becoming Familiar with MQUAD</h3>
                     <h2>The Home Workspace Features</h2>
                     <p><img src="Content/Images/home_Screen.png" alt="Home Screen" /></p>
                     <p>The Home workspace provides an overview of the content of a project. Extra information about items on the Homespace can be fobtained by moving the cursor over these items. </p>
                     <p>Most items you see on any MQUAD are active: the information or action they represent can be accessed by clicking on them. </p>
                     <p>• The upper left panel of the Home workspace contains a summary of your project’s attributes and buttons to import and export data. You can also import data to and export data from individual Workspaces by clicking on the Import or Export button at the top of the panel for that Workspace.
                        • The top of some Workspace panels also features an Edit icon. When you click on Edit some panels will turn orange to remind you to switch out of Edit mode when you are finished editing.
                        • You can expand individual Workspaces (charts, tables, plots) to full screen by clicking the Expand icon. When you are done, simply close that window by clicking the X to close.
                        • When you move your cursor over different icons or objects in the Project, Smart Tool Tips will pop up to answer questions you may have.
                     </p>
                     <p>If you are using MQUAD for the first time, MQUAD will open on the Demo project, a mixed methods study of literacy development. The Demo aims to provide the opportunity to explore MQUAD and see what can be done in MQUAD. </p>
                     <p>Returning users will see the project they most recently visited. </p>
                     <p>To create a new project or to access another project, you need to open the Project homespace by clicking on the Project Tab in the Main Menu bar. </p>
                     <h2>The Main Menu Bar</h2>
                     <p><img src="Content/Images/Main_Menu_Bar.png" alt="Main Menu Bar" />
                        Located at the top, it allows to access different workspaces within the open project. The Back button allows to go back in MQUAD.
                     </p>
                     <h2>Saving Your Work</h2>
                     <p>Generally, data submitted to a MQUAD project are automatically saved in real-time so you never have to worry about losing data. Uploading media, creating and tagging excerpts, linking media to descriptors... do not require any active 'save' action. </p>
                     <p>Saving is only required when syncing transcript sections to excerpts on video and audio streams, when creating or editing a text file, and after writing a memo. A Save button will pop up when you are required to save.##!image </p>
                     <p>Logging out of MQUAD is as simple as clicking the logout button in the MQUAD header.</p>
                     <p>It is still a good idea to create backup copies of your work. You will find more information about this process in <a href="blog/backing-up-and-managing-your-data.html" title="Backing Up and Managing Your Data Blog">Backing Up and Managing Your Data Blog </a></p>

                     <h3>Combining and Analyzing Mixed Method Data</h3>
                     <p>Let's begin here by looking at a picture of one way qualitative and quantitative data can be linked together. The left column illustrates the flow from 'Fieldwork' to 'Generate New Themes,' summarizes much of what takes place in basic qualitative research. On the other hand, the more logical positivist (or empiricist) rules for quantitative research are more tightly constrained by guidelines for how data are to be collected, hypotheses defined, planned analyses, and results reported. But, if the questions under study can be better represented by both types of data, we need ways to bring them in touch with each other so more complex questions can be considered during analysis. In this exemplar model, ratings or dimensions of qualitative themes are generated, explored, and integrated with other quantitative data. By doing so, they serve as a mechanism for moving back and forth between the two types of data and allow easy access to the best evidence for particular questions - sometimes qualitative, sometimes quantitative, and sometimes both. In Dedoose, these ratings are the codes weights/ratings that Dedoose uses to build visualizations that expose patterns in these complex relationships (Lieber &amp; Weisner, 2010, '<em>Meeting the practical challenges of mixed methods research.</em>' In A. Tashakkori &amp; C. Teddlie (Eds.) Sage Handbook of Mixed Methods in Social &amp; Behavioral Research, 2nd Edition (pp. 559-579). Thousand Oaks, CA: SAGE Publications).</p>

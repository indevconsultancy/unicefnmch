<div class="webinarText">
<p>
This is a recording of one of our regular free Dedoose intro webinars led by Dr. Lieber (one of our founders).
We include some background history of the Dedoose conception and development and then jump into the app itself.
After a brief peek at the Dedoose Account and Projects Workspaces, we do a 'shallow' dive, building a project from
scratch--importing media, creating codes, excerpting and tagging content, modifying the code tree, basic retrieval,
and linking to descriptor data. At that point, we believe anyone new to Dedoose can get up and running.
We then take a quick look at the Dedoose survey importer before jumping back to Dr. Lieber's demo project to
explore the rest of what Dedoose has to offer including, the Security Center where user access privileges are
controlled, dealing with PDFs, images, and video/audio, features to build and assess inter-rater reliability (IRR),
memos, and a good sampling of Dedoose analytic, visualization, and filter capabilities. Finally, we wrap with some
Q&A and discuss some of what is coming soon to Dedoose 8.1 (can you say descriptive statistics?).
</p>
